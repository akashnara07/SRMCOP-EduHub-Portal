// Generate read-only Academic History for a student
export function getStudentAcademicHistory(student: StudentMaster, allRecords: StudentAcademicRecord[]): AcademicHistoryItem[] {
  const records = allRecords.filter(r => r.studentId === student.id);
  
  // Build timeline items sorted by academic year
  const sortedYears = ['2023-2024', '2024-2025', '2025-2026', '2026-2027'];
  const items: AcademicHistoryItem[] = [];

  sortedYears.forEach(year => {
    const rec = records.find(r => r.academicYear === year);
    if (rec) {
      const isCurrent = year === '2026-2027';
      const isPast = year < '2026-2027';
      
      items.push({
        academicYear: year,
        programme: rec.programme,
        semesters: `Semester ${rec.semester}${rec.programme === 'B.Pharm' ? ` & ${rec.semester + 1}` : ''}`,
        section: rec.section,
        facultyAdvisor: rec.facultyAdvisor,
        status: isPast ? 'Completed' : (isCurrent ? 'Currently Enrolled' : 'Upcoming'),
        gpa: isPast ? 'N/A' : (isCurrent ? 'In Progress' : 'Pending'),
        attendance: isPast ? 'N/A' : (isCurrent ? 'N/A' : 'N/A'),
        creditsEarned: rec.registeredCourses.length * 4
      });
    } else {
      // If student was enrolled in past years based on batch
      const [startYr] = (student.batch || '2023-2027').split('-').map(Number);
      const yearStart = parseInt(year.split('-')[0]);
      if (yearStart >= startYr && yearStart < 2026) {
        items.push({
          academicYear: year,
          programme: student.programme,
          semesters: `Year ${yearStart - startYr + 1}`,
          section: 'Section A',
          facultyAdvisor: 'Dr. V. Chitra',
          status: year < '2026-2027' ? 'Completed' : 'Currently Enrolled',
          gpa: year < '2026-2027' ? 'N/A' : 'In Progress',
          attendance: 'N/A',
          creditsEarned: 24
        });
      }
    }
  });

  return items;
}

/**
 * Search student by RegNo OR Official Email / Personal Email / Name
 */
export function findStudentByRegNoOrEmail(identifier: string): StudentMaster | undefined {
  if (!identifier) return undefined;
  const q = identifier.toLowerCase().trim();
  const list = getStudentsMaster();

  // 1. Exact match by RegNo, Official Email, Personal Email, or Full Name
  const exact = list.find(s => 
    s.regNo.toLowerCase() === q ||
    (s.officialEmail && s.officialEmail.toLowerCase() === q) ||
    (s.email && s.email.toLowerCase() === q) ||
    s.name.toLowerCase() === q ||
    `${s.regNo.toLowerCase()}@srmcop.edu.in` === q
  );
  if (exact) return exact;

  // 2. Partial or prefix match
  return list.find(s =>
    q.includes(s.regNo.toLowerCase()) ||
    s.regNo.toLowerCase().includes(q) ||
    s.name.toLowerCase().includes(q) ||
    (s.officialEmail && s.officialEmail.toLowerCase().includes(q))
  );
}

/**
 * Update Official Email for a student matched by Registration Number
 */
export function updateStudentOfficialEmail(regNo: string, officialEmail: string): boolean {
  const list = getStudentsMaster();
  const q = regNo.toLowerCase().trim();
  const index = list.findIndex(s => s.regNo.toLowerCase() === q);

  if (index === -1) return false;

  list[index].officialEmail = officialEmail.trim();
  list[index].emailAssigned = Boolean(officialEmail.trim());
  list[index].loginEnabled = Boolean(officialEmail.trim());
  if (list[index].status === 'Email Pending' && officialEmail.trim()) {
    list[index].status = 'Login Enabled';
  }
  
  saveStudentsMaster(list);
  return true;
}

/**
 * Promote student in master database without duplicating student record
 */
export function promoteStudentInMaster(
  regNo: string,
  nextAcademicYear: string,
  nextYear: string,
  nextSemester: string
): boolean {
  const list = getStudentsMaster();
  const index = list.findIndex(s => s.regNo.toLowerCase() === regNo.toLowerCase().trim());
  if (index === -1) return false;

  const current = list[index];

  // Record history
  const historyItem = {
    academicYear: current.academicYear || '2025-2026',
    programme: current.programme,
    currentYear: current.currentYear || 'Year III',
    semester: current.semester || 'Semester V',
    section: current.section || 'Section A',
    regulation: current.regulation || 'PCI-2020',
    promotedAt: new Date().toISOString().split('T')[0],
    status: 'Promoted'
  };

  if (!current.enrollmentHistory) {
    current.enrollmentHistory = [];
  }
  current.enrollmentHistory.push(historyItem);

  // Update master fields
  current.academicYear = nextAcademicYear;
  current.currentYear = nextYear;
  current.semester = nextSemester;

  if (nextYear === 'Graduated' || nextSemester === 'Graduated') {
    current.status = 'Graduated';
  }

  saveStudentsMaster(list);
  return true;
}

