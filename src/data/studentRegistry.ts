export type StudentStatus = 
  | 'Active' 
  | 'Login Enabled' 
  | 'Login Disabled' 
  | 'Email Pending' 
  | 'Graduated' 
  | 'Alumni' 
  | 'Suspended';

export type ProgrammeType = 'B.Pharm' | 'Pharm.D' | 'M.Pharm';

export interface StudentMaster {
  id: string; // Primary internal ID e.g. "std-1"
  name: string;
  regNo: string; // Permanent primary identifier e.g. "SRM2026PH7810"
  programme: ProgrammeType;
  regulation: string; // e.g. "PCI-2014", "PCI-2020", "PCI-2024"
  admissionYear: number | string; // e.g. 2023
  expectedGraduation: number | string; // e.g. 2027
  batch: string; // e.g. "2023-2027"
  
  // Current Structured Academic Info
  academicYear: string; // e.g. "2026-2027"
  currentYear: string; // e.g. "Year IV"
  semester: string; // e.g. "Semester VII"
  section?: string; // e.g. "Section A"
  
  // Status & Authentication
  status: StudentStatus;
  officialEmail?: string;
  emailAssigned: boolean;
  loginEnabled: boolean;
  accountActivated: boolean;
  firebaseUid?: string;
  
  // Contact & Personal Details
  email?: string; // Personal email
  phone?: string;
  dob?: string;
  gender?: string;
  dateOfAdmission?: string;
  fatherName?: string;
  motherName?: string;
  address?: string;

  // Historical Enrollment Records
  enrollmentHistory?: {
    academicYear: string;
    programme: ProgrammeType;
    currentYear: string;
    semester: string;
    section?: string;
    regulation?: string;
    promotedAt?: string;
    status?: string;
  }[];
}

export interface RegisteredCourse {
  id: string;
  courseCode: string;
  courseName: string;
  semester: number;
  type?: 'Core' | 'Elective' | 'Practical';
}

export interface StudentAcademicRecord {
  id: string;
  studentId: string;
  academicYear: string; // e.g. "2025-2026"
  programme: ProgrammeType;
  semester: number;
  section: string; // e.g. "Section A"
  facultyAdvisor: string; // e.g. "Dr. V. Chitra"
  registeredCourses: RegisteredCourse[];
}

export interface AcademicHistoryItem {
  academicYear: string;
  programme: ProgrammeType;
  semesters: string; // e.g. "Semesters 1 & 2"
  section: string;
  facultyAdvisor: string;
  status: 'Completed' | 'Currently Enrolled' | 'Upcoming';
  gpa?: string;
  attendance?: string;
  creditsEarned?: number;
}

