export function getStudentsMaster(): StudentMaster[] {
  let list: StudentMaster[] = DEFAULT_STUDENTS_MASTER;
  if (typeof localStorage !== 'undefined') {
    try {
      const raw = localStorage.getItem(STORAGE_KEY_STUDENTS);
      if (raw) list = JSON.parse(raw);
    } catch (e) {
      console.error('Error reading student master:', e);
    }
  }

  // Ensure all 30 Pharm.D Year V students are present and merged without duplication
  let listModified = false;
  const mergedList = [...list];

  // Helper to sync DEFAULT_STUDENTS_MASTER items missing in stored list
  DEFAULT_STUDENTS_MASTER.forEach(defStudent => {
    const existingIndex = mergedList.findIndex(
      s => s.regNo && defStudent.regNo && s.regNo.toLowerCase() === defStudent.regNo.toLowerCase()
    );
    if (existingIndex === -1) {
      mergedList.push(defStudent);
      listModified = true;
    } else {
      // Merge missing fields only, do not overwrite existing profile info
      const existing = mergedList[existingIndex];
      let itemUpdated = false;
      const updatedItem = { ...existing };

      if (!updatedItem.programme && defStudent.programme) { updatedItem.programme = defStudent.programme; itemUpdated = true; }
      if (!updatedItem.regulation && defStudent.regulation) { updatedItem.regulation = defStudent.regulation; itemUpdated = true; }
      if (!updatedItem.status && defStudent.status) { updatedItem.status = defStudent.status; itemUpdated = true; }
      if (updatedItem.programme === 'Pharm.D' && updatedItem.semester !== '') { updatedItem.semester = ''; itemUpdated = true; }
      
      if (defStudent.enrollmentHistory && defStudent.enrollmentHistory.length > 0) {
        if (!updatedItem.enrollmentHistory) updatedItem.enrollmentHistory = [];
        defStudent.enrollmentHistory.forEach(defHist => {
          const hasHist = updatedItem.enrollmentHistory!.some(h => h.academicYear === defHist.academicYear);
          if (!hasHist) {
            updatedItem.enrollmentHistory!.push(defHist);
            itemUpdated = true;
          }
        });
      }

      if (itemUpdated) {
        mergedList[existingIndex] = updatedItem;
        listModified = true;
      }
    }
  });

  if (listModified && typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem(STORAGE_KEY_STUDENTS, JSON.stringify(mergedList));
    } catch (e) {
      console.error('Error auto-syncing student master:', e);
    }
  }

  // Ensure B.Pharm students have PCI 2017/2026 regulation, and Pharm.D students have no semester string
  return mergedList.map(s => {
    if (s.programme === 'Pharm.D') {
      const { semester, ...rest } = s;
      return { ...rest, semester: '', regulation: s.regulation || 'PCI 2008' };
    }
    if (s.programme === 'B.Pharm') {
      const isFirstYear = s.currentYear === 'First Year' || s.currentYear === 'Year I' || s.semester === 'Semester I' || s.semester === 'Semester II';
      if ((s.academicYear === '2026-2027' || !s.academicYear) && isFirstYear && s.regulation === 'PCI 2026') {
        return { ...s, regulation: 'PCI 2026' };
      }
      if (s.regulation === 'PCI-2020' || s.regulation === 'PCI 2020' || !s.regulation) {
        return { ...s, regulation: 'PCI 2017' };
      }
    }
    return s;
  });
}

/**
 * Projects master student records into session-specific workspace view
 * for 2026-2027 (Active) or 2025-2026 (Historical Session) without duplicating Master Student records.
 */
export function getStudentsForAcademicSession(
  session: string = '2026-2027',
  masterList?: StudentMaster[]
): StudentMaster[] {
  const master = masterList || getStudentsMaster();

  // Active Current Academic Session (2026-2027)
  if (session === '2026-2027' || !session) {
    return master.map(s => ({
      ...s,
      academicYear: '2026-2027',
      ...(s.programme === 'Pharm.D' ? { semester: '' } : {})
    }));
  }

  // Historical Session (2025-2026)
  if (session === '2025-2026') {
    return master.map(s => {
      let projYear = s.currentYear;
      let projSem = s.semester;

      if (s.programme === 'B.Pharm') {
        if (s.currentYear === 'Second Year' || s.semester === 'Semester III' || s.semester === 'Semester IV') {
          projYear = 'First Year';
          projSem = 'Semester I';
        } else if (s.currentYear === 'Third Year' || s.semester === 'Semester V' || s.semester === 'Semester VI') {
          projYear = 'Second Year';
          projSem = 'Semester III';
        } else if (s.currentYear === 'Fourth Year' || s.semester === 'Semester VII' || s.semester === 'Semester VIII') {
          projYear = 'Third Year';
          projSem = 'Semester V';
        } else {
          projYear = 'First Year';
          projSem = 'Semester I';
        }
      } else if (s.programme === 'Pharm.D') {
        projSem = '';
        if (s.currentYear === 'Year II') {
          projYear = 'Year I';
        } else if (s.currentYear === 'Year III') {
          projYear = 'Year II';
        } else if (s.currentYear === 'Year IV') {
          projYear = 'Year III';
        } else if (s.currentYear === 'Year V') {
          projYear = 'Year IV';
        } else if (s.currentYear === 'Year VI') {
          projYear = 'Year V';
        } else {
          projYear = 'Year I';
        }
      } else if (s.programme === 'M.Pharm') {
        if (s.currentYear === 'Second Year' || s.semester === 'Semester III' || s.semester === 'Semester IV') {
          projYear = 'First Year';
          projSem = 'Semester I';
        } else {
          projYear = 'First Year';
          projSem = 'Semester I';
        }
      }

      return {
        ...s,
        academicYear: '2025-2026',
        currentYear: projYear,
        semester: s.programme === 'Pharm.D' ? '' : projSem
      };
    });
  }

  // Default projection for other sessions
  return master.map(s => ({
    ...s,
    academicYear: session,
    ...(s.programme === 'Pharm.D' ? { semester: '' } : {})
  }));
}

export function parseSemesterNumber(semStr?: string, yearStr?: string): number {
  const str = `${semStr || ''} ${yearStr || ''}`.toUpperCase();
  if (/\b(VIII|SEMESTER\s*8|SEM\s*8|8)\b/i.test(str)) return 8;
  if (/\b(VII|SEMESTER\s*7|SEM\s*7|7)\b/i.test(str)) return 7;
  if (/\b(VI|SEMESTER\s*6|SEM\s*6|6)\b/i.test(str)) return 6;
  if (/\b(V|SEMESTER\s*5|SEM\s*5|5)\b/i.test(str)) return 5;
  if (/\b(IV|SEMESTER\s*4|SEM\s*4|4)\b/i.test(str)) return 4;
  if (/\b(III|SEMESTER\s*3|SEM\s*3|3)\b/i.test(str)) return 3;
  if (/\b(II|SEMESTER\s*2|SEM\s*2|2)\b/i.test(str)) return 2;
  if (/\b(I|SEMESTER\s*1|SEM\s*1|1)\b/i.test(str)) return 1;
  return 1;
}

export function parsePharmDYearNumber(yearStr?: string): number {
  if (!yearStr) return 1;
  const str = yearStr.toUpperCase();
  if (/\b(VI|6TH|SIXTH|INTERNSHIP)\b/i.test(str)) return 6;
  if (/\b(V|5TH|FIFTH)\b/i.test(str)) return 5;
  if (/\b(IV|4TH|FOURTH)\b/i.test(str)) return 4;
  if (/\b(III|3RD|THIRD)\b/i.test(str)) return 3;
  if (/\b(II|2ND|SECOND)\b/i.test(str)) return 2;
  if (/\b(I|1ST|FIRST)\b/i.test(str)) return 1;
  const match = str.match(/\d+/);
  return match ? parseInt(match[0], 10) : 1;
}

export function getEnrolledCoursesForStudent(
  student: Partial<StudentMaster>,
  selectedSession?: string
): RegisteredCourse[] {
  if (!student) return [];

  const programme = student.programme || 'B.Pharm';
  const session = selectedSession || student.academicYear || '2026-2027';

  // Determine effective currentYear and semester based on selectedSession
  let effectiveYear = student.currentYear || '';
  let effectiveSem = student.semester || '';

  if (selectedSession && student.id && student.enrollmentHistory) {
    const histMatch = student.enrollmentHistory.find(h => h.academicYear === selectedSession);
    if (histMatch) {
      effectiveYear = histMatch.currentYear || (histMatch as any).currentYearLevel || effectiveYear;
      effectiveSem = histMatch.semester || effectiveSem;
    }
  }

  // Determine Regulation
  let regulation = student.regulation || '';
  if (!regulation) {
    if (programme === 'B.Pharm') {
      const isFirstYear = effectiveYear === 'First Year' || effectiveYear === 'Year I' || effectiveSem === 'Semester I' || effectiveSem === 'Semester II';
      if ((session === '2026-2027' || !session) && isFirstYear) {
        regulation = 'PCI 2026';
      } else {
        regulation = 'PCI 2017';
      }
    } else if (programme === 'Pharm.D') {
      regulation = 'PCI 2008';
    } else if (programme === 'M.Pharm') {
      regulation = 'PCI 2017 PG';
    }
  }

  // STRICT RULE FOR B.PHARM PCI 2026:
  // "Every PCI 2026 student should show 'No subjects assigned' until curriculum allocation is intentionally performed.
  // No placeholder subjects. No copied PCI 2017 subjects. No dummy data."
  if (programme === 'B.Pharm' && regulation === 'PCI 2026') {
    return [];
  }

  try {
    const db = getCurriculumDb();
    if (db && db.courseInformation && db.courseInformation.length > 0) {
      if (programme === 'Pharm.D') {
        // Pharm.D is Year-based only. Never assign subjects using Semester. Semester must remain NULL.
        const yrNum = parsePharmDYearNumber(effectiveYear);

        const matchedCourses = db.courseInformation.filter(c => {
          const progMatch = (c.programme || '').toLowerCase().trim() === 'pharm.d';
          const yrMatch = c.year === yrNum || String(c.year) === String(yrNum);
          return progMatch && yrMatch;
        });

        if (matchedCourses.length > 0) {
          return matchedCourses.map((c, idx) => ({
            id: `c-dyn-${c.subjectCode}-${idx}`,
            courseCode: c.subjectCode,
            courseName: c.courseName,
            semester: c.year || yrNum,
            type: (c.subjectType as 'Core' | 'Elective' | 'Practical') || 'Core'
          }));
        }
      } else {
        // B.Pharm (PCI 2017) / M.Pharm
        const semNum = parseSemesterNumber(effectiveSem, effectiveYear);

        const matchedCourses = db.courseInformation.filter(c => {
          const progMatch = (c.programme || 'B.Pharm').toLowerCase().trim() === programme.toLowerCase().trim();
          const semMatch = c.semester === semNum || String(c.semester) === String(semNum);
          const regMatch = !regulation || regulation === 'PCI 2017' || !c.regulation || c.regulation === regulation;
          return progMatch && semMatch && regMatch;
        });

        if (matchedCourses.length > 0) {
          return matchedCourses.map((c, idx) => ({
            id: `c-dyn-${c.subjectCode}-${idx}`,
            courseCode: c.subjectCode,
            courseName: c.courseName,
            semester: c.semester || semNum,
            type: (c.subjectType as 'Core' | 'Elective' | 'Practical') || 'Core'
          }));
        }
      }
    }
  } catch (e) {
    console.error('Error computing enrolled courses:', e);
  }

  const records = getAcademicRecords();
  const rec = records.find(r => r.studentId === student.id);
  return rec?.registeredCourses || [];
}

